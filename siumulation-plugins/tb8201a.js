  const bus = busOf(pid); let yp=0; bus.forEach(q=>{ if (S.cable[q.id]){ const RL=LOADZ[loadOf(q.id)]; yp += 1/(2*portRs(q.id)+RL); } });
  const zp = yp? 1/yp : 1e12; const vb = voc*zp/(zp+2*o.zc); o.vbus=vb; o.busN=bus.length;
  const RL = o.plugged? LOADZ[loadOf(pid)] : 1e12; o.v = vb*RL/(RL+2*o.rs); o.RL=RL;
  if (sg.unit==='dBu'){ o.dbu=V2dBu(o.v); o.ok = o.plugged && RL>1 && Math.abs(o.dbu-voc0)<6.5; o.txt=`Card ${fmtLv(voc0,sg)} open-circuit, ${fmtZ(2*o.zc)} source → ${bus.length>1?bus.length+' outputs share contacts '+port(pid).pair+' · bus '+V2dBu(vb).toFixed(2)+' dBu → ':''}${o.rs? '2 × '+o.rs+' Ω build-out → ':''}${o.plugged? 'load '+fmtZ(RL):'no cable (open)'} → ${o.v>0?o.dbu.toFixed(2)+' dBu':'0 V'}`; }
